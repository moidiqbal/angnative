// Stage the self-contained Angular bundle (generated by `pnpm bundle:quickjs`)
// as an app asset so the shell can boot Angular inside the QuickJS runtime.
// Skipped when the bundle has not been generated, so a plain build still works.
val copyAngNativeBundle by tasks.registering(Copy::class) {
  val bundle = rootProject.file("../../dist/aot/quickjs-bundle.js")
  onlyIf { bundle.exists() }
  from(bundle)
  into(file("src/main/assets"))
  rename { "angnative-bundle.js" }
}
tasks.named("preBuild") { dependsOn(copyAngNativeBundle) }
