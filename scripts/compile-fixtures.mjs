#!/usr/bin/env node
/**
 * compile-fixtures.mjs — generate the minimal "hello world" entry consumed by
 * the JS size gate (`bundle:fixtures` → `check-size-budget.mjs`).
 *
 * NOTE: This is intentionally not an Angular AOT compile. There is no ngc
 * pipeline wired up yet (see CLI dev.ts "placeholder for ngc call"). It emits
 * a small hand-written ESM entry that exercises the same production defines
 * the gate checks for, so the gate has a deterministic input on a fresh
 * checkout. Replace this with a real ngc compile when the AOT pipeline lands.
 */

import { mkdirSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(repoRoot, 'packages', 'testing', 'fixtures', 'out');
const entryPath = join(outDir, 'app.js');

const entry = `/**
 * Generated by scripts/compile-fixtures.mjs — do not edit.
 * Minimal hello-world entry for the JS size gate.
 */
import { Component, signal } from '@angular/core';

export class HelloWorldComponent {
  clicks = signal(0);

  increment() {
    this.clicks.update((n) => n + 1);
  }

  template = '<na-view><na-text>Hello AngNative</na-text></na-view>';
}

export function bootstrap() {
  return new HelloWorldComponent();
}
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(entryPath, entry, 'utf-8');
console.log(`Wrote ${entryPath}`);
